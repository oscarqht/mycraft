interface BlockBuilderInput {
  id: number;
  key: string;
  name: string;
  category: BlockCategory;
  renderType?: BlockRenderType;
  solid?: boolean;
  selectable?: boolean;
  transparent?: boolean;
  isFluid?: boolean;
  hardness?: number;
  preferredTool?: ToolType;
  minTier?: number;
  toolType?: ToolType;
  toolTier?: number;
  toolSpeed?: number;
  foodPoints?: number;
  maxStack?: number;
  dropId?: number;
  dropCount?: number;
  lightLevel?: number;
  tintType?: 'none' | 'grass' | 'foliage' | 'water';
  soundGroup?: BlockDef['soundGroup'];
  faces?: Partial<BlockFaces> | string;
  itemTexture?: string;
  particleColor: string;
}

function def(input: BlockBuilderInput): BlockDef {
  const renderType = input.renderType ?? 'opaque';
  const tex = typeof input.faces === 'string' ? input.faces : input.key;
  const faces: BlockFaces =
    typeof input.faces === 'object' && input.faces !== null
      ? {
          top: input.faces.top ?? tex,
          side: input.faces.side ?? tex,
          bottom: input.faces.bottom ?? input.faces.top ?? tex,
          front: input.faces.front,
        }
      : { top: tex, side: tex, bottom: tex };

  return {
    id: input.id,
    key: input.key,
    name: input.name,
    category: input.category,
    renderType,
    solid: input.solid ?? (renderType === 'opaque' || renderType === 'cutout' || renderType === 'slab_low'),
    selectable: input.selectable ?? (renderType !== 'air' && renderType !== 'fluid' && renderType !== 'item'),
    transparent: input.transparent ?? (renderType !== 'opaque'),
    isFluid: input.isFluid ?? (renderType === 'fluid'),
    hardness: input.hardness ?? 1.0,
    preferredTool: input.preferredTool ?? 'none',
    minTier: input.minTier ?? 0,
    toolType: input.toolType,
    toolTier: input.toolTier,
    toolSpeed: input.toolSpeed,
    foodPoints: input.foodPoints,
    maxStack: input.maxStack ?? (input.toolType ? 1 : 64),
    dropId: input.dropId ?? input.id,
    dropCount: input.dropCount ?? 1,
    lightLevel: input.lightLevel ?? 0,
    tintType: input.tintType ?? 'none',
    soundGroup: input.soundGroup ?? 'stone',
    faces,
    itemTexture: input.itemTexture,
    particleColor: input.particleColor,
  };
}

